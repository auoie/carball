//! The engine's Rust bindings (src/engine_ffi.rs, committed) are bindgen's of its C interface (engine/capi/rlengine.h)
//! as it is now: made again here, any difference fails. `CARBALL_WRITE_BINDINGS=1` writes them instead
//! (scripts/gen_bindings.sh, after a change to the header). Needs libclang (bindgen loads it at run time) and rustfmt,
//! the toolchain's the images build with (Dockerfile: Rust 1.91.1; another's may lay the file out otherwise, a
//! difference with no change in the header, RV-1014): with no libclang the check is skipped, said on stderr (the builds
//! need neither: only this check, where libclang is installed, as on the development machine), unless
//! `CARBALL_REQUIRE_BINDINGS=1` (a check run that must have it fails instead, RV-1013)

use std::io::Write;

const HEADER: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../engine/capi/rlengine.h");
const BINDINGS: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/src/engine_ffi.rs");
const RUSTFMT_CONFIG: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../rustfmt.toml");

/// The bindings, bindgen's options their only source (its version pinned in Cargo.toml): the engine's functions, its
/// two structs and the event constants; the arena opaque; formatted as `cargo fmt` formats the crate
fn generate() -> String {
    bindgen::Builder::default()
        .header(HEADER)
        // (one target, whatever the machine: the interface's types are fixed-width, `size_t` as `usize`, and the
        // structs' layouts are asserted at compile time, so the browser's wasm32 build checks them too)
        .clang_arg("--target=x86_64-unknown-linux-gnu")
        .allowlist_function("rl_.*")
        .allowlist_type("RLControls|RLCarNetInfo|CarballArena")
        .allowlist_var("RL_EVENT_.*")
        .opaque_type("CarballArena")
        .derive_default(true)
        .derive_partialeq(true)
        .derive_eq(true)
        // (the Rust the images build with, Dockerfile; pinned too, bindgen's output following it)
        .rust_target(bindgen::RustTarget::stable(91, 1).unwrap())
        .rust_edition(bindgen::RustEdition::Edition2024)
        .raw_line("//! The engine's C interface (engine/capi/rlengine.h) as Rust, generated by bindgen: never edited by hand.")
        .raw_line("//! After a change to the header: scripts/gen_bindings.sh (tests/engine_bindings.rs checks it)")
        .raw_line("#![allow(non_camel_case_types)]")
        .rustfmt_configuration_file(Some(RUSTFMT_CONFIG.into()))
        .generate()
        .unwrap_or_else(|e| panic!("bindgen, {HEADER}: {e}"))
        .to_string()
}

#[test]
fn the_committed_bindings_are_bindgens_of_the_header() {
    let write = std::env::var_os("CARBALL_WRITE_BINDINGS").is_some();
    if let Err(e) = clang_sys::load() {
        let required = std::env::var("CARBALL_REQUIRE_BINDINGS").is_ok_and(|v| v == "1");
        assert!(!write && !required, "no libclang, which bindgen needs: {e}");
        // (straight to stderr, past the test harness's capture: a skip is seen)
        let _ =
            writeln!(std::io::stderr(), "SKIPPED: src/engine_ffi.rs not checked against the header: no libclang ({e})");
        return;
    }
    let made = generate();
    if write {
        std::fs::write(BINDINGS, &made).unwrap_or_else(|e| panic!("{BINDINGS}: {e}"));
        return;
    }
    let committed = std::fs::read_to_string(BINDINGS).unwrap_or_else(|e| panic!("{BINDINGS}: {e}"));
    if committed != made {
        let (line, (old, new)) = committed
            .lines()
            .chain(std::iter::repeat(""))
            .zip(made.lines().chain(std::iter::repeat("")))
            .enumerate()
            .find(|(_, (old, new))| old != new)
            .unwrap();
        panic!(
            "src/engine_ffi.rs isn't bindgen's of engine/capi/rlengine.h as it is now: run scripts/gen_bindings.sh \
             (line {}: committed {old:?}, made {new:?})",
            line + 1
        );
    }
}
