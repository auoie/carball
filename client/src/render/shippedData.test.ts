import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/** What ships carries no game data (RV-99): no mesh's vertices or UVs, no traced shapes, in any module under src/ (the
 *  arena's and its surroundings' shapes are rules, named measures, statistics and fits). Numbers in comments don't
 *  ship, so they're left out. */
const SRC = new URL("..", import.meta.url).pathname;
const ROOT = new URL("../../..", import.meta.url).pathname;
const ASSETS = join(ROOT, "out/bsim/assets_local/arena");
const PLAN = join(ASSETS, "field_plan.json");

function modules(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return modules(path);
    return name.endsWith(".ts") && !name.endsWith(".test.ts") && !name.endsWith(".d.ts") ? [path] : [];
  });
}

/** A module's numeric literals, comments stripped: each with its value and how many decimals it was written with */
function numbers(source: string): { value: number; decimals: number; at: number }[] {
  const code = source.replace(/\/\*[\s\S]*?\*\//g, (c) => " ".repeat(c.length)).replace(/\/\/[^\n]*/g, (c) => " ".repeat(c.length));
  return [...code.matchAll(/(?<![A-Za-z_$\d.])-?\d+(\.\d*)?(?:e-?\d+)?/g)].map((m) => ({
    value: Number(m[0]),
    decimals: m[1] ? m[1].length - 1 : 0,
    at: m.index,
  }));
}

const FIELD_AND_GOAL = ["render/stadiumFieldRules.ts", "render/stadiumField.ts", "render/goalInterior.ts", "render/gameSurfaces.ts", "render/themes/stadiumSurroundings.ts"];

describe("what ships carries no game data (RV-99)", () => {
  it("the field's, goals' and surroundings' modules hold rules, not traced shapes: each under a thousand numbers", () => {
    for (const path of FIELD_AND_GOAL) {
      let source = readFileSync(join(SRC, path), "utf8");
      // (FIELD_LIGHT's lightmap statistics aside: numbers, not shapes)
      source = source.replace(/export const FIELD_LIGHT[\s\S]*?\n};\n/, "");
      expect(numbers(source).length, path).toBeLessThan(1000);
    }
  });
});

/** A 2D lookup of points by 1 uu cells */
class Grid {
  readonly #cells = new Map<number, number[]>();
  add(a: number, b: number): void {
    const key = Math.floor(a) * 1e6 + Math.floor(b);
    const cell = this.#cells.get(key);
    if (cell) cell.push(a, b);
    else this.#cells.set(key, [a, b]);
  }
  near(a: number, b: number, tolerance: number): boolean {
    for (let i = -1; i <= 1; i++) {
      for (let j = -1; j <= 1; j++) {
        const cell = this.#cells.get((Math.floor(a) + i) * 1e6 + Math.floor(b) + j) ?? [];
        for (let k = 0; k < cell.length; k += 2) if (Math.hypot((cell[k] ?? 0) - a, (cell[k + 1] ?? 0) - b) <= tolerance) return true;
      }
    }
    return false;
  }
}

function objFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? objFiles(path) : name.endsWith(".obj") ? [path] : [];
  });
}

const OBJS = objFiles(join(ASSETS, "meshes"));

describe.skipIf(OBJS.length === 0)("against the game's meshes and the traced plan (local)", () => {
  // Every vertex as its axis pairs (|x|, |y|), (|x|, |z|), (|y|, |z|); every UV, as a pair and its components
  const coords = new Grid();
  const uvPairs = new Grid();
  const uvValues: number[] = [];
  for (const path of OBJS) {
    for (const line of readFileSync(path, "utf8").split("\n")) {
      if (line.startsWith("v ")) {
        const [x, y, z] = line.split(/\s+/).slice(1, 4).map((c) => Math.abs(Number(c)));
        coords.add(x ?? 0, y ?? 0);
        coords.add(x ?? 0, z ?? 0);
        coords.add(y ?? 0, z ?? 0);
      } else if (line.startsWith("vt ")) {
        const [u, v] = line.split(/\s+/).slice(1, 3).map(Number);
        // (UVs at 1000x: a pair within 0.0005 is within 0.5 of a cell's)
        uvPairs.add((u ?? 0) * 1000, (v ?? 0) * 1000);
        uvValues.push(u ?? 0, v ?? 0);
      }
    }
  }
  // The traced plan's points too (local: generated by scripts/field_plan.py)
  if (existsSync(PLAN)) {
    const walk = (o: unknown): void => {
      if (Array.isArray(o) && o.length > 1 && o.every((c) => typeof c === "number")) {
        const q = o.length % 2 === 1 ? o.slice(1) : o;
        for (let i = 0; i + 1 < q.length; i += 2) coords.add(Math.abs(q[i] ?? 0), Math.abs(q[i + 1] ?? 0));
      } else if (Array.isArray(o)) o.forEach(walk);
      else if (o && typeof o === "object") Object.values(o).forEach(walk);
    };
    walk(JSON.parse(readFileSync(PLAN, "utf8")));
  }
  const sorted = Float64Array.from(uvValues).sort();
  const nearUv = (x: number, tolerance: number): boolean => {
    let lo = 0;
    let hi = sorted.length;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      if ((sorted[mid] ?? 0) < x) lo = mid + 1;
      else hi = mid;
    }
    return Math.abs((sorted[lo] ?? Infinity) - x) <= tolerance || Math.abs((sorted[lo - 1] ?? Infinity) - x) <= tolerance;
  };

  /** The longest run of consecutive hits in a module's numbers (pairs in both phases, or single values) */
  function longestRun(source: string, step: 1 | 2, hit: (a: { value: number; decimals: number }, b?: { value: number; decimals: number }) => boolean): { length: number; at: string } {
    const n = numbers(source);
    let best = { length: 0, at: "" };
    for (let phase = 0; phase < step; phase++) {
      let run: number[] = [];
      for (let i = phase; i + step - 1 < n.length; i += step) {
        const a = n[i];
        const b = step === 2 ? n[i + 1] : undefined;
        if (a && hit(a, b)) run.push(i);
        else run = [];
        const first = n[run[0] ?? 0];
        if (run.length > best.length && first) best = { length: run.length, at: source.slice(first.at, first.at + 80).replace(/\s+/g, " ") };
      }
    }
    return best;
  }

  // (a pair counts when it could be a traced point: both coordinates 10 uu or more, one of them off the 16 uu grid the
  // arena's design measures share with our rules, 128, 256, 512 ...)
  const traced = (a: number, b: number): boolean => {
    const [x, y] = [Math.abs(a), Math.abs(b)];
    return Math.max(x, y) >= 100 && Math.min(x, y) >= 10 && (x % 16 !== 0 || y % 16 !== 0);
  };

  it.each(modules(SRC).map((p) => p.slice(SRC.length)))("%s: no run of 3 coordinate pairs on the meshes' vertices or the traced plan (within 0.6 uu)", (path) => {
    const source = readFileSync(join(SRC, path), "utf8");
    const run = longestRun(source, 2, (a, b) => !!b && traced(a.value, b.value) && coords.near(Math.abs(a.value), Math.abs(b.value), 0.6));
    expect(run.length, `${path}: ${run.at}`).toBeLessThan(3);
  });

  it.each(modules(SRC).map((p) => p.slice(SRC.length)))("%s: no run of 3 UV pairs, nor of 4 four-decimal values, from the meshes' UVs", (path) => {
    const source = readFileSync(join(SRC, path), "utf8");
    const large = (x: { value: number; decimals: number }, places: number): boolean => x.decimals >= places && Math.abs(x.value) >= 0.05;
    const pairs = longestRun(source, 2, (a, b) => !!b && large(a, 3) && large(b, 3) && uvPairs.near(a.value * 1000, b.value * 1000, 0.5));
    expect(pairs.length, `${path}: ${pairs.at}`).toBeLessThan(3);
    // (each within half its last written decimal of a UV component: the old goal-side glass chart's V row, RV-99; never
    // the small values under 0.05, as dense among the UVs as in a measured profile's tail, Curve_Smoke's)
    const values = longestRun(source, 1, (a) => large(a, 4) && nearUv(a.value, 0.5 * 10 ** -a.decimals));
    expect(values.length, `${path}: ${values.at}`).toBeLessThan(4);
  });
});
